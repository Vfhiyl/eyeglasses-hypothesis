#!/usr/bin/env python3
"""B1 post-audit gate: remeasure + assert audit invariants (2026-08-12).

The 2026-08-06..08-10 "dual SESOI+5 PASS_RAW freeze" was retracted: it was
manufactured by an outcome-aware curation layer (see
docs/B1_CURATION_AUDIT_2026-08-12.md). This gate now asserts the CORRECTED
state instead:

- outcome-aware layer removed + retraction recorded in the verdict
- SESOI+15 not claimed anywhere (must FAIL*)
- corrected_primary arm present in the sensitivity table
- wearer–control collisions active == 0

Exit 0 on pass, 1 on fail. Does not start servers or npm builds.
"""
from __future__ import annotations

import csv
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
TABLES = ROOT / "outputs" / "tables"
OUT_MD = TABLES / "b1_freeze_gate_report.md"


def run(script: str) -> None:
    env = os.environ.copy()
    env["B1_SPARQL"] = "0"
    for k in (
        "http_proxy",
        "https_proxy",
        "HTTP_PROXY",
        "HTTPS_PROXY",
        "ALL_PROXY",
        "all_proxy",
    ):
        env.pop(k, None)
    subprocess.run(
        [sys.executable, str(SCRIPTS / script)],
        cwd=ROOT,
        env=env,
        check=True,
    )


def _read(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main() -> int:
    for script in (
        "25_b1_primary_estimand.py",
        "27_b1_output_estimand.py",
        "29_b1_cleaning_sensitivity.py",
        "30_b1_wearer_control_collision_audit.py",
    ):
        print("run", script)
        run(script)

    checks: list[tuple[str, bool, str]] = []

    verdict = {r["check"]: r for r in _read(TABLES / "b1_roster_verdict.csv")}
    for key, want_prefix in (
        ("outcome_aware_layer_removed", "DONE"),
        ("pass_era_sesoi5_pass_raw", "RETRACTED"),
        ("wearer_control_collision_clear", "DONE"),
    ):
        got = (verdict.get(key) or {}).get("result") or ""
        ok = got.startswith(want_prefix)
        checks.append((key, ok, f"got={got}"))

    mac = (verdict.get("sesoi_macfarlane_15_primary") or {}).get("result") or ""
    checks.append(("sesoi_macfarlane_15_primary_FAIL", mac.startswith("FAIL"), f"got={mac}"))

    # output summary: record the corrected span verdict; assert +15 not claimed
    out_sum = _read(TABLES / "b1_output_estimand_summary.csv")
    span = next(
        (r for r in out_sum if r.get("estimand") == "output_span_after_45"),
        out_sum[0] if out_sum else {},
    )
    sesoi5 = span.get("sesoi5") or ""
    checks.append(
        (
            "output_sesoi5_recorded",
            bool(sesoi5),
            f"sesoi5={sesoi5} (recorded, not asserted)",
        )
    )
    sesoi15 = span.get("sesoi15") or ""
    if sesoi15:
        checks.append(
            (
                "output_sesoi15_not_pass",
                not sesoi15.startswith("PASS"),
                f"sesoi15={sesoi15}",
            )
        )

    sens = _read(TABLES / "b1_labor_cleaning_sensitivity.csv")

    def _arm(r: dict[str, str]) -> str:
        return (r.get("mode") or r.get("arm") or "").strip()

    corr = next((r for r in sens if _arm(r) == "corrected_primary"), None)
    dep = next((r for r in sens if _arm(r) == "overlay_exclude_layer"), None)
    checks.append(
        (
            "sensitivity_corrected_primary_present",
            corr is not None,
            f"corrected={None if not corr else corr.get('sesoi5')}",
        )
    )
    checks.append(
        (
            "sensitivity_deprecated_layer_labeled",
            dep is not None and "DEPRECATED" in (dep.get("note") or ""),
            f"deprecated_note={'' if not dep else (dep.get('note') or '')[:60]}",
        )
    )
    plus15_ok = True
    bad_arm = ""
    for r in sens:
        if (r.get("sesoi15") or "").startswith("PASS"):
            plus15_ok = False
            bad_arm = _arm(r)
            break
    checks.append(
        (
            "sensitivity_plus15_none_pass",
            plus15_ok,
            "all arms FAIL +15" if plus15_ok else f"arm={bad_arm} PASS +15",
        )
    )

    coll = _read(TABLES / "b1_wearer_control_collision_audit.csv")
    active = [r for r in coll if r.get("severity") == "COLLISION_ACTIVE_CONTROL"]
    checks.append(("collision_active_zero", len(active) == 0, f"n_active={len(active)}"))

    lines = [
        "# B1 post-audit gate report",
        "",
        "Regenerated by `scripts/31_b1_freeze_gate.py` (audit-corrected 2026-08-12).",
        "The pass-era dual SESOI+5 freeze is RETRACTED; this gate asserts the",
        "corrected state (see `docs/B1_CURATION_AUDIT_2026-08-12.md`).",
        "",
        "| Check | OK | Detail |",
        "|-------|----|--------|",
    ]
    all_ok = True
    for name, ok, detail in checks:
        all_ok = all_ok and ok
        lines.append(f"| {name} | {'PASS' if ok else 'FAIL'} | {detail} |")
    lines += [
        "",
        f"**Gate:** {'PASS' if all_ok else 'FAIL'}",
        "",
        "Historical freeze claim (`b1_claim_freeze_package.md`) is superseded.",
        "",
    ]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT_MD)
    for name, ok, detail in checks:
        print(("OK" if ok else "FAIL"), name, detail)
    print("GATE", "PASS" if all_ok else "FAIL")
    return 0 if all_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
